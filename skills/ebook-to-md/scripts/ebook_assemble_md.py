#!/usr/bin/env python3
"""Assemble structured text and OCR Markdown into book.md."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any


PAGE_RE = re.compile(r"page-(\d+)", re.IGNORECASE)


def page_number(path: Path) -> int | None:
    match = PAGE_RE.search(path.stem)
    return int(match.group(1)) if match else None


def read_json(path: Path) -> dict[str, Any] | None:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def collect_ocr_markdown(run_dir: Path) -> dict[int, Path]:
    ocr_dir = run_dir / "ocr"
    if not ocr_dir.exists():
        return {}
    result: dict[int, Path] = {}
    for path in sorted(ocr_dir.glob("*.md")):
        number = page_number(path)
        if number is not None:
            result[number] = path
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description="Assemble ebook Markdown from page-aligned outputs.")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--input", default=".", help="Run directory containing manifests and OCR outputs.")
    parser.add_argument("--output", default=".", help="Directory for book.md.")
    parser.add_argument("--lang", default="kor+eng", help="Language hint recorded in output comment.")
    parser.add_argument("--max-pages", type=int, default=0, help="Optional maximum pages to assemble; 0 means all.")
    parser.add_argument("--wait-ms", type=int, default=700, help="Recorded wait time for consistency.")
    parser.add_argument("--turn-key", default="ArrowRight", help="Recorded turn key for consistency.")
    args = parser.parse_args()

    run_dir = Path(args.input)
    capture_manifest = read_json(run_dir / "capture-manifest.json") or {"pages": []}
    ocr_manifest = read_json(run_dir / "ocr-manifest.json") or {"pages": []}
    ocr_by_page = collect_ocr_markdown(run_dir)

    title = capture_manifest.get("bookTitle") or "Converted Ebook"
    pages = capture_manifest.get("pages") or []
    if args.max_pages:
        pages = pages[: args.max_pages]

    lines = [
        f"# {title}",
        "",
        "<!-- Generated by ebook-to-md. Review OCR confidence and capture warnings before treating as final text. -->",
        f"<!-- language: {args.lang}; turn-key: {args.turn_key}; wait-ms: {args.wait_ms} -->",
        "",
    ]
    warnings: list[str] = []

    for page in pages:
        index = int(page.get("pageIndex") or 0)
        text_path = page.get("textPath")
        source_path: Path | None = None
        if text_path and (run_dir / text_path).exists():
            source_path = run_dir / text_path
        elif index in ocr_by_page:
            source_path = ocr_by_page[index]

        if source_path is None:
            warnings.append(f"Page {index}: no text or OCR Markdown found.")
            continue

        content = source_path.read_text(encoding="utf-8").strip()
        if not content:
            warnings.append(f"Page {index}: source text is empty.")
            continue
        lines.append(f"<!-- page {index:04d}: {source_path.relative_to(run_dir)} -->")
        lines.append(content)
        lines.append("")

    if warnings:
        lines.append("<!-- Assembly warnings:")
        lines.extend(f"- {warning}" for warning in warnings)
        lines.append("-->")
        lines.append("")

    # Keep ocr_manifest referenced so schema drift is noticed during execution.
    if ocr_manifest.get("warnings"):
        lines.append("<!-- OCR manifest warnings present; inspect ocr-report.md. -->")
        lines.append("")

    book_md = "\n".join(lines)
    if args.dry_run:
        print(book_md)
        return 0

    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    (output / "book.md").write_text(book_md, encoding="utf-8")
    print(output / "book.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
